def unique_series(rows):
    """Conflicting values on the same day are excluded, never averaged."""
    groups={}
    for day,v in rows:
        if v is None:continue
        try:
            value=float(v)
        except (TypeError,ValueError,OverflowError):continue
        if not math.isfinite(value):continue
        label=str(day)[:10]
        try:date.fromisoformat(label)
        except ValueError:continue
        groups.setdefault(label,set()).add(value)
    return pd.Series({d:next(iter(v)) for d,v in sorted(groups.items()) if len(v)==1},dtype=float)


def catalog(state,now):
    """Use fixed adapters. Failures are reported per source, not hidden."""
    items={};issues=[]
    last=now.astimezone(ROME).date()
    def add(key,label,unit,grain,scope,source,url,status,origin,rows,remote=True):
        s=unique_series(rows)
        if s.empty:return
        if grain=="gas_day":
            s=s[s.index<=closed_gas_day(now).isoformat()]
        else:s=s[s.index<=str(last)]
        if len(s):items[key]=Series(key,label,unit,grain,scope,source,url,status,origin,s,remote)
    def attempt(name,fn):
        try:fn()
        except (ValueError,KeyError,TypeError,AttributeError,IndexError,OSError,ArithmeticError):
            issues.append(name+" · dati non validabili")
    def gas(bundle,prefix,scope,status):
        frame=inspect(bundle,now).usable
        grain="gas_day" if bundle.origin.grain=="daily" else "month"
        for k in ("demand_gwh","industry_gwh","distribution_gwh","power_gwh","imports_gwh","production_gwh","exports_gwh"):
            if k in frame and k in bundle.origin.fields:
                add(prefix+"_"+k,FIELDS[k],"GWh/giorno gas" if grain=="gas_day" else "GWh/mese",
                    grain,scope,"JRC ENaGaD" if prefix=="jrc" else "Fonte di mercato selezionata",
                    bundle.origin.url or "",status,bundle.fingerprint,
                    ((str(d.date()),v) for d,v in frame[k].items()))
    def weather():
        from .weather_source import archive,SCOPE
        from .weather import SOURCE as WEATHER_URL
        item=archive(state,now)
        if not item:return
        f=item["frame"]
        for k,label,unit in (("temperature_c","Temperatura media proxy","°C"),("hdd","HDD Open-Meteo base 18 °C","°C · giorno")):
            add("weather_"+k,label,unit,"gas_day",SCOPE,"Open-Meteo · ERA5 (CC BY 4.0)",WEATHER_URL,
                "Rianalisi storica, ritardo 7 giorni; non previsione archiviata"+(" · ultimo dato valido da aggiornare" if item["failed"] else ""),
                item["acquired"].isoformat(),zip(f.index.date,f[k]))
    attempt("Open-Meteo",weather)
    attempt("JRC",lambda:gas(jrc_archive(),"jrc","Italia","Archivio 2015–2021; include stime della fonte"))
    bundles=dict(state.get("live_public_bundles_v1",{}))
    b=state.get("active_bundle")
    if b is not None and b.origin.kind in (Kind.HISTORICAL,Kind.LIVE) and not b.origin.archive:
        bundles.setdefault(b.origin.grain,b)
    for grain,b in bundles.items():
        if grain not in ("daily","monthly") or b.origin.archive or b.origin.kind not in (Kind.HISTORICAL,Kind.LIVE):continue
        attempt("Mercato "+grain,lambda:gas(b,"market_"+grain,"Rete SRG" if grain=="daily" else "Italia",
             "Dato pubblico caricato; verificare data e revisioni"))
    def lng():
        r=state.get("acer_lng_result_v1") or bundled_lng()
        # No arbitrary metadata from imported files.
        for k,label in (("eu","Prezzo GNL UE"),("benchmark","Benchmark GNL – TTF")):
            add("acer_"+k,label,"€/MWh","publication_day","UE","ACER TERMINAL",TERMINAL,
                "Serie storica; possibile cache/revisione, non prezzo attuale",r.sha256,
                ((x["date"],x[k]) for x in r.rows))
    attempt("ACER",lng)
    def mase():
        rows=[r for r in observations() if r["geography"]=="IT" and len(r["period"])==4]
        add("mase_production","Produzione nazionale annua","mld Sm³","year","Italia","MASE UNMIG",MASE_SOURCE,
            "Trascrizioni degli archivi annuali, edizioni diverse","archivi MASE inclusi",
            ((r["period"]+"-01-01",as_bcm(r["value"],r["unit"])) for r in rows))
    attempt("MASE",mase)
    def native():
        f=state.get("jarvis_native_v1",{}).get("frame")
        if f is None:return
        for phase in ("provvisorio","definitivo"):
            for metric,k in (("Totale Prelevato","withdrawal"),("Totale Immesso","injection")):
                sub=f[(f.family=="bilanci")&(f.metric==metric)&(f.unit=="GWh")&(f.edition==phase)]
                add("jarvis_"+k+"_"+phase,metric+" · "+phase,"GWh/giorno gas","gas_day","SRG","Snam Jarvis",JARVIS,
                    "Importazione dichiarata; unità inferita da PCS, timestamp assente",
                    sha256("|".join(sorted(set(sub.sha256))).encode()).hexdigest(),zip(sub.gas_day,sub.value))
    attempt("Bilanci Jarvis",native)
    def coefficients():
        f=state.get("jarvis_native_v1",{}).get("frame")
        if f is None:return
        subset=f[f.family.isin(("wkr","wkr_csv","qk","gas_stock","gas_stock_hs2"))]
        groups=subset.groupby(["family","edition","metric","unit"],sort=True)
        for i,((family,edition,metric,unit),part) in enumerate(groups):
            if i>=240:
                issues.append("Coefficienti e stock Jarvis · catalogo limitato a 240 serie")
                break
            # Distinct declared editions and units; do not join forecast coef/stock
            # values as measured gas days. Dynamic source labels stay local only.
            key="jarvis_coef_"+sha256(json.dumps([family,edition,metric,unit],ensure_ascii=False).encode()).hexdigest()[:20]
            ident=sha256("|".join(sorted(set(part.sha256))).encode()).hexdigest()
            add(key,str(metric)[:120],str(unit)[:60],"declared_day",str(edition)[:120],
                "Snam Jarvis · "+family,JARVIS,"Valore pubblicato; può includere stime/proiezioni; non misura certificata",
                ident,zip(part.gas_day,part.value),False)
    attempt("WKR / qk / Gas Stock",coefficients)
    def annual():
        annual=state.get("snam_forecast_annual_v1",{})
        if not annual:return
        f=pd.concat([x["frame"] for x in annual.values()],ignore_index=True)
        v,_=daily_vintages(f,now.astimezone(ROME).replace(tzinfo=None))
        q=v[v.h==-1]
        origin=sha256("|".join(sorted(x["sha256"] for x in annual.values())).encode()).hexdigest()
        for k,label,unit in (("demand","Riconsegnato G−1","unità native/giorno gas"),("injection","Immesso G−1","unità native/giorno gas"),("hdd","HDD medio ponderale","gradi giorno")):
            add("snam_"+k,label,unit,"gas_day","SRG · pubblicazione G−1","Snam Jarvis",JARVIS,
                "Consuntivo provvisorio; cutoff 15:00; unità native da confermare",
                origin,zip(q.target.dt.date,q[k]))
    attempt("Annuali Jarvis",annual)
    def power():
        hist=merge([],state.get("terna_history_v1",[]))
        by={}
        for b in hist:
            acquired=stamp(b["acquired_at"])
            if acquired>now:continue
            for row in b["rows"]:
                key=(row["day"],row["metric"])
                old=by.get(key)
                if old is None or acquired>old[0]:
                    by[key]=(acquired,{row["gwh"]},{batch_id(b)})
                elif acquired==old[0]:
                    old[1].add(row["gwh"]);old[2].add(batch_id(b))
        # If no archived history, offer the complete observed session acquisition.
        if not by:
            p=state.get("terna_power_v1",{}).get("power")
            if p:
                acquired=stamp(p["acquired"])
                if acquired<=now:
                    for r in p["rows"]:
                        if r["metric"] in METRICS and r["gwh"] is not None and r["valid_slots"]==r["expected_slots"] and r["expected_slots"]>0:
                            key=(r["gas_day"],r["metric"])
                            if key not in by:by[key]=(acquired,set(),set())
                            by[key][1].add(float(r["gwh"]))
        labels={"Thermal":"Termoelettrico (tutti i combustibili)","Wind":"Eolico","Photovoltaic":"Fotovoltaico","Hydro":"Idroelettrico","Geothermal":"Geotermico","load":"Fabbisogno elettrico"}
        for metric,label in labels.items():
            filtered=[(d,t,vs,ids) for (d,m),(t,vs,ids) in by.items() if m==metric and len(vs)==1]
            if not filtered:continue
            origin=sha256("|".join(sorted(set().union(*(x[3] for x in filtered))) or [max(x[1] for x in filtered).isoformat()]).encode()).hexdigest()
            add("terna_"+metric,label,"GWh elettrici/giorno gas","gas_day","Italia elettrica","Terna",PORTAL,
                "Giorni completi osservati; convenzione intervallo sperimentale; ultima versione dichiarata",
                origin,((d,next(iter(vs))) for d,t,vs,ids in filtered))
        # Use only equal-day complete metrics from the same acquisition.
        residual=[];origins=set()
        for day,_ in sorted({(d,"") for d,m in by}):
            group=[by.get((day,m)) for m in ("load","Wind","Photovoltaic")]
            if not all(x and len(x[1])==1 for x in group) or len({x[0] for x in group})!=1:continue
            if group[0][2] and not set.intersection(*(x[2] for x in group)):continue
            l,w,s=(next(iter(x[1])) for x in group)
            residual.append((day,l-w-s))
            origins.update(group[0][2] or {group[0][0].isoformat()})
        if residual:
            add("terna_residual_wind_solar","Carico al netto di eolico e fotovoltaico","GWh elettrici/giorno gas","gas_day","Italia elettrica","Terna · elaborazione I.G.O.R.",PORTAL,
                "Consuntivo; proxy parziale, non domanda di gas; non sottrae import e altre produzioni",sha256("|".join(sorted(origins)).encode()).hexdigest(),residual)
    attempt("Terna",power)
    def industry():
        from .terna_context import STATE,SELECT,scopes,latest_rows
        batches=state.get(STATE,[])
        options=scopes(batches,"industry")
        selected=state.get(SELECT,{}).get("industry")
        if selected in options:options=[selected]+[x for x in options if x!=selected]
        for scope in options[:12]:
            ident=sha256(json.dumps(scope).encode()).hexdigest()[:16]
